function pairwise_cv_bodipy_new_num()
% PAIRWISE_CV_BODIPY_NEW_NUM
% Stratified 5-fold cross-validation for pairwise BODIPY dye
% classification, run against data/processed_combined -- the
% current dataset/pipeline (superseding bodipy_old, which the previous
% draft of this validation study was run against).
%
% Reproduces the exact preprocessing, sample-balancing (600
% brightness-filtered molecules/dye), CNN architecture, and training
% hyperparameters of bodipy_new_num/analyze_bodipy_pairs.m, replacing
% only its single 70/15/15 split with proper stratified 5-fold CV.
% Reports mean +/- std of accuracy, precision, recall, F1 (macro) for
% every one of the 91 unique pairs among the 14 available dyes.
%
% IMPORTANT: an earlier version of this script used the WRONG
% architecture -- a single-branch CNN carried over by mistake from the
% deprecated bodipy_old/step2b_cnn_spectra.m, despite a code comment
% incorrectly claiming it matched analyze_bodipy_pairs.m. This version
% uses the actual dual-branch architecture in analyze_bodipy_pairs.m
% (Branch 1: conv(16)-BN-ReLU-maxpool-conv(32)-BN-ReLU-maxpool-dropout
% -FC(32); Branch 2: avgpool(1x5)-FC(32); concatenated), which matches
% Figure 4A of the manuscript. This was confirmed against the
% manuscript's own reported numbers: the existing single-split baseline
% (results/original_single_split/pseudomix/matrices.mat, generated by the real
% analyze_bodipy_pairs.m) has exactly 54/91 pairs with accuracy > 0.7
% and a max of 0.911 for pair 1-13 -- matching the manuscript's text
% ("accuracy exceeds 0.7 for 54 pairs... largest value is 0.91... IN-1
% and IN-13") exactly. The single-branch architecture used previously
% does not correspond to anything in the manuscript.
%
% Also fixes the F1 metric: previously computed as the harmonic mean of
% MACRO-averaged precision and recall (2*P*R/(P+R) using the already-
% averaged P, R), which is not the same quantity as the standard
% macro-F1 (the mean of each class's own F1 score) whenever per-class
% precision/recall diverge. This version tracks per-class
% precision/recall per fold and reports genuine macro-F1.
%
% Results are checkpointed to disk after every pair so a partial run
% survives an interruption. A representative trained network (the pair
% closest to the median accuracy) is retrained and saved for
% interpretability analysis (see cnn_weight_analysis.m).


% Resolve paths relative to this script's own location, so the script runs
% correctly regardless of MATLAB's current working directory.
repo_root = fileparts(fileparts(fileparts(mfilename('fullpath'))));
rng(42, 'twister');
try
    parallel.gpu.enableCUDAForwardCompatibility(true);
catch
    % No GPU / older MATLAB -- training will fall back to CPU.
end

data_dir = fullfile('data', 'processed_combined');
cutoff_val = 1000;
n_per_dye = 600;
k_folds = 5;

target_bodipy = [1:7, 9:15]; % matches bodipy_new_num/analyze_bodipy_pairs.m (dye 8 not available)
n_dyes = length(target_bodipy);

out_dir = fullfile(repo_root, 'results', 'cross_validation');
if ~exist(out_dir, 'dir')
    mkdir(out_dir);
end
results_file = fullfile(out_dir, 'pairwise_cv_results.mat');

n_pairs_total = nchoosek(n_dyes, 2);
all_results = repmat(struct('dye1', nan, 'dye2', nan, 'n_per_dye', nan, ...
    'skipped', false, 'mean_accuracy', nan, 'std_accuracy', nan, ...
    'mean_precision', nan, 'std_precision', nan, 'mean_recall', nan, ...
    'std_recall', nan, 'mean_f1', nan, 'std_f1', nan, ...
    'all_fold_metrics', []), n_pairs_total, 1);

pair_idx = 0;
t_start = tic;

for i1 = 1:n_dyes
    for i2 = (i1+1):n_dyes
        pair_idx = pair_idx + 1;
        dye1 = target_bodipy(i1);
        dye2 = target_bodipy(i2);

        fprintf('\n[%d/%d] BODIPY %d vs %d (elapsed %.1f min)\n', ...
            pair_idx, n_pairs_total, dye1, dye2, toc(t_start)/60);

        [dye1_rois, ok1] = load_and_filter(data_dir, dye1, cutoff_val);
        [dye2_rois, ok2] = load_and_filter(data_dir, dye2, cutoff_val);

        all_results(pair_idx).dye1 = dye1;
        all_results(pair_idx).dye2 = dye2;
        all_results(pair_idx).n_per_dye = n_per_dye;

        if ~ok1 || ~ok2 || size(dye1_rois,3) < n_per_dye || size(dye2_rois,3) < n_per_dye
            fprintf('  Skipping: insufficient samples (dye%d n=%d, dye%d n=%d, need %d)\n', ...
                dye1, size(dye1_rois,3), dye2, size(dye2_rois,3), n_per_dye);
            all_results(pair_idx).skipped = true;
            save(results_file, 'all_results');
            continue;
        end

        i_idx = randperm(size(dye1_rois,3), n_per_dye);
        j_idx = randperm(size(dye2_rois,3), n_per_dye);
        dye1_rois = dye1_rois(:,:,i_idx);
        dye2_rois = dye2_rois(:,:,j_idx);

        all_data = cat(3, dye1_rois, dye2_rois);
        all_labels = categorical([zeros(n_per_dye,1); ones(n_per_dye,1)]);
        sz3 = size(all_data);
        all_data = reshape(all_data, [sz3(1), sz3(2), 1, sz3(3)]);

        cv = cvpartition(all_labels, 'KFold', k_folds, 'Stratify', true);
        fold_metrics = zeros(k_folds, 8); % acc, prec_macro, rec_macro, f1_macro, prec_c1, prec_c2, rec_c1, rec_c2

        for fold = 1:k_folds
            [net, val_data_f, val_labels_f] = train_pairwise_fold(all_data, all_labels, cv, fold);
            val_pred = classify(net, val_data_f);
            cm = confusionmat(val_labels_f, val_pred);
            [acc, prec_macro, rec_macro, f1_macro, prec_c, rec_c] = calculate_metrics_full(cm);
            fold_metrics(fold, :) = [acc, prec_macro, rec_macro, f1_macro, prec_c(1), prec_c(2), rec_c(1), rec_c(2)];
            fprintf('    Fold %d/%d: Acc=%.4f Prec=%.4f Rec=%.4f F1(true macro)=%.4f\n', ...
                fold, k_folds, acc, prec_macro, rec_macro, f1_macro);
        end

        mean_metrics = mean(fold_metrics, 1);
        std_metrics = std(fold_metrics, 1);

        all_results(pair_idx).mean_accuracy = mean_metrics(1);
        all_results(pair_idx).std_accuracy = std_metrics(1);
        all_results(pair_idx).mean_precision = mean_metrics(2);
        all_results(pair_idx).std_precision = std_metrics(2);
        all_results(pair_idx).mean_recall = mean_metrics(3);
        all_results(pair_idx).std_recall = std_metrics(3);
        all_results(pair_idx).mean_f1 = mean_metrics(4);
        all_results(pair_idx).std_f1 = std_metrics(4);
        all_results(pair_idx).mean_precision_per_class = mean_metrics(5:6);
        all_results(pair_idx).mean_recall_per_class = mean_metrics(7:8);
        all_results(pair_idx).all_fold_metrics = fold_metrics;

        fprintf('  Pair %d-%d: Acc=%.3f+/-%.3f Prec=%.3f+/-%.3f Rec=%.3f+/-%.3f F1=%.3f+/-%.3f\n', ...
            dye1, dye2, mean_metrics(1), std_metrics(1), mean_metrics(2), std_metrics(2), ...
            mean_metrics(3), std_metrics(3), mean_metrics(4), std_metrics(4));

        % Checkpoint after every pair.
        save(results_file, 'all_results');
    end
end

fprintf('\nAll pairs complete in %.1f minutes.\n', toc(t_start)/60);

write_summary(out_dir, all_results, cutoff_val, n_per_dye);
% Raw per-fold metrics alongside the summary, so the reported mean +/- std can
% be independently recomputed rather than taken on faith.
write_folds_csv(out_dir, all_results);
save_reference_net(data_dir, cutoff_val, n_per_dye, all_results, out_dir);

end

function write_folds_csv(out_dir, all_results)
% Writes the per-fold accuracy/precision/recall/F1 underlying pairwise_cv_summary.txt.
% Column order matches all_fold_metrics as built in the main loop:
% [accuracy, precision_macro, recall_macro, f1_macro, precision_c1, precision_c2,
%  recall_c1, recall_c2].
csv_path = fullfile(out_dir, 'pairwise_cv_folds.csv');
fid = fopen(csv_path, 'w');
if fid < 0
    warning('Could not open %s for writing; per-fold CSV not saved.', csv_path);
    return;
end
fprintf(fid, ['dye1,dye2,fold,accuracy,precision_macro,recall_macro,f1_macro,' ...
    'precision_dye1,precision_dye2,recall_dye1,recall_dye2\n']);
for i = 1:numel(all_results)
    r = all_results(i);
    if isnan(r.dye1) || r.skipped || isempty(r.all_fold_metrics)
        continue;
    end
    M = r.all_fold_metrics;
    for f = 1:size(M, 1)
        fprintf(fid, '%d,%d,%d', r.dye1, r.dye2, f);
        fprintf(fid, ',%.6f', M(f, :));
        fprintf(fid, '\n');
    end
end
fclose(fid);
fprintf('Per-fold metrics written to %s\n', csv_path);
end

function [rois, ok] = load_and_filter(data_dir, dye_id, cutoff_val)
    fpath = fullfile(data_dir, sprintf('bodipy%d.mat', dye_id));
    if ~exist(fpath, 'file')
        rois = [];
        ok = false;
        return;
    end
    d = load(fpath);
    sel = d.n_photons_combined > cutoff_val;
    rois = d.spectral_rois_combined(:,:,sel);
    centroid = d.spectral_centroids_combined(sel);
    [~, rm] = rmoutliers(centroid, 'mean', 'thresholdfactor', 4);
    rois = rois(:,:,~rm);
    ok = true;
end

function [net, val_data, val_labels] = train_pairwise_fold(all_data, all_labels, cv, fold)
    train_idx = cv.training(fold);
    val_idx = cv.test(fold);

    train_data = all_data(:,:,:,train_idx);
    train_labels = all_labels(train_idx);
    val_data_raw = all_data(:,:,:,val_idx);
    val_labels = all_labels(val_idx);

    sz = size(train_data);
    lgraph = pairwise_layer_graph(sz, numel(categories(all_labels)));

    augmenter = imageDataAugmenter('RandXReflection', true, 'RandYReflection', false);
    aug_train = augmentedImageDatastore([sz(1) sz(2) sz(3)], train_data, train_labels, 'DataAugmentation', augmenter);
    val_data = augmentedImageDatastore([sz(1) sz(2) sz(3)], val_data_raw, val_labels);

    options = trainingOptions('sgdm', ...
        'InitialLearnRate', 0.001, ...
        'MaxEpochs', 200, ...
        'Shuffle', 'every-epoch', ...
        'ValidationData', val_data, ...
        'ValidationFrequency', 30, ...
        'Verbose', false, ...
        'Plots', 'none');

    net = trainNetwork(aug_train, lgraph, options);
end

function lgraph = pairwise_layer_graph(sz, n_labels)
    % Dual-branch architecture -- matches bodipy_new_num/analyze_bodipy_pairs.m
    % and manuscript Figure 4A exactly (Branch 1: conv(16)/conv(32)
    % convolutional path; Branch 2: average-pooled direct path;
    % concatenated before the final classifier).
    inputLayer = imageInputLayer([sz(1) sz(2) sz(3)], 'Name', 'input');

    convLayers = [
        convolution2dLayer(3, 16, 'Padding', 'same', 'Name', 'conv1')
        batchNormalizationLayer('Name', 'bn1')
        reluLayer('Name', 'relu1')
        maxPooling2dLayer(2, 'Stride', 2, 'Name', 'pool1')
        convolution2dLayer(3, 32, 'Padding', 'same', 'Name', 'conv2')
        batchNormalizationLayer('Name', 'bn2')
        reluLayer('Name', 'relu2')
        maxPooling2dLayer(2, 'Stride', 2, 'Name', 'pool2')
        dropoutLayer(0.5, 'Name', 'dropout')
        fullyConnectedLayer(32, 'Name', 'fc_conv')];

    flattenInputLayer = [
        averagePooling2dLayer([1, 5], 'Name', 'gap_input')
        fullyConnectedLayer(32, 'Name', 'fc_input')];

    concatLayer = concatenationLayer(1, 2, 'Name', 'concat');

    finalLayers = [
        reluLayer('Name', 'relu_concat')
        fullyConnectedLayer(n_labels, 'Name', 'fc_final')
        softmaxLayer('Name', 'softmax')
        classificationLayer('Name', 'classOutput')];

    lgraph = layerGraph(inputLayer);
    lgraph = addLayers(lgraph, convLayers);
    lgraph = addLayers(lgraph, flattenInputLayer);
    lgraph = addLayers(lgraph, concatLayer);
    lgraph = addLayers(lgraph, finalLayers);

    lgraph = connectLayers(lgraph, 'input', 'conv1');
    lgraph = connectLayers(lgraph, 'input', 'gap_input');
    lgraph = connectLayers(lgraph, 'fc_conv', 'concat/in1');
    lgraph = connectLayers(lgraph, 'fc_input', 'concat/in2');
    lgraph = connectLayers(lgraph, 'concat', 'relu_concat');
end

function [accuracy, precision_macro, recall_macro, f1_macro, precision_per_class, recall_per_class] = calculate_metrics_full(confusion_matrix)
    % Genuine macro-F1: the mean of each class's own F1 score, NOT the
    % harmonic mean of macro-averaged precision and recall (those two
    % quantities differ whenever per-class precision/recall diverge).
    num_classes = size(confusion_matrix, 1);
    precision_per_class = zeros(1, num_classes);
    recall_per_class = zeros(1, num_classes);
    f1_per_class = zeros(1, num_classes);
    for c = 1:num_classes
        TP = confusion_matrix(c, c);
        FP = sum(confusion_matrix(:, c)) - TP;
        FN = sum(confusion_matrix(c, :)) - TP;
        if (TP + FP) > 0
            precision_per_class(c) = TP / (TP + FP);
        end
        if (TP + FN) > 0
            recall_per_class(c) = TP / (TP + FN);
        end
        if (precision_per_class(c) + recall_per_class(c)) > 0
            f1_per_class(c) = 2 * precision_per_class(c) * recall_per_class(c) / (precision_per_class(c) + recall_per_class(c));
        end
    end
    precision_macro = mean(precision_per_class);
    recall_macro = mean(recall_per_class);
    f1_macro = mean(f1_per_class);
    accuracy = trace(confusion_matrix) / sum(confusion_matrix(:));
end

function write_summary(out_dir, all_results, cutoff_val, n_per_dye)
    fid = fopen(fullfile(out_dir, 'pairwise_cv_summary.txt'), 'w');
    fprintf(fid, 'Pairwise CNN Classification (bodipy_new_num) - Stratified 5-Fold CV Results\n');
    fprintf(fid, '===========================================================================\n\n');
    fprintf(fid, 'Photon cutoff: %d\n', cutoff_val);
    fprintf(fid, 'Samples per dye: %d (balanced)\n', n_per_dye);
    fprintf(fid, 'Architecture: dual-branch (conv1=16, conv2=32), matches manuscript Fig. 4A\n');
    fprintf(fid, 'F1 = genuine macro-F1 (mean of per-class F1)\n\n');
    fprintf(fid, 'Dye Pair   Accuracy         Precision        Recall           F1\n');
    fprintf(fid, '--------   ----------       ----------       ----------       ----------\n');
    for i = 1:length(all_results)
        r = all_results(i);
        if isnan(r.dye1)
            continue;
        end
        if r.skipped
            fprintf(fid, '%2d-%-2d      SKIPPED (insufficient samples)\n', r.dye1, r.dye2);
        else
            fprintf(fid, '%2d-%-2d      %.3f+/-%.3f     %.3f+/-%.3f     %.3f+/-%.3f     %.3f+/-%.3f\n', ...
                r.dye1, r.dye2, r.mean_accuracy, r.std_accuracy, r.mean_precision, r.std_precision, ...
                r.mean_recall, r.std_recall, r.mean_f1, r.std_f1);
        end
    end
    fclose(fid);
    fprintf('Summary written to %s\n', fullfile(out_dir, 'pairwise_cv_summary.txt'));
end

function save_reference_net(data_dir, cutoff_val, n_per_dye, all_results, out_dir)
    % Retrain fold 1 of the pair closest to the median CV accuracy and
    % save the resulting net + real ROI images/labels, for use by
    % cnn_weight_analysis.m.
    valid = ~arrayfun(@(r) isnan(r.dye1) || r.skipped, all_results);
    accs = arrayfun(@(r) r.mean_accuracy, all_results(valid));
    dye1s = arrayfun(@(r) r.dye1, all_results(valid));
    dye2s = arrayfun(@(r) r.dye2, all_results(valid));

    if isempty(accs)
        warning('No valid pairs to build a reference net from.');
        return;
    end

    med = median(accs);
    [~, ref_idx] = min(abs(accs - med));
    ref_dye1 = dye1s(ref_idx);
    ref_dye2 = dye2s(ref_idx);
    fprintf('\nRetraining reference net for interpretability: BODIPY %d vs %d (acc=%.3f, median=%.3f)\n', ...
        ref_dye1, ref_dye2, accs(ref_idx), med);

    [dye1_rois, ~] = load_and_filter(data_dir, ref_dye1, cutoff_val);
    [dye2_rois, ~] = load_and_filter(data_dir, ref_dye2, cutoff_val);
    i_idx = randperm(size(dye1_rois,3), n_per_dye);
    j_idx = randperm(size(dye2_rois,3), n_per_dye);
    dye1_rois = dye1_rois(:,:,i_idx);
    dye2_rois = dye2_rois(:,:,j_idx);

    all_data = cat(3, dye1_rois, dye2_rois);
    all_labels = categorical([zeros(n_per_dye,1); ones(n_per_dye,1)]);
    sz3 = size(all_data);
    all_data = reshape(all_data, [sz3(1), sz3(2), 1, sz3(3)]);

    cv = cvpartition(all_labels, 'KFold', 5, 'Stratify', true);
    [net, ~, ~] = train_pairwise_fold(all_data, all_labels, cv, 1);

    val_idx = cv.test(1);
    roi_data = all_data(:,:,:,val_idx); %#ok<NASGU>
    roi_labels = all_labels(val_idx); %#ok<NASGU>

    d1 = load(fullfile(data_dir, sprintf('bodipy%d.mat', ref_dye1)));
    wl = d1.wl; %#ok<NASGU>
    reference_pair = [ref_dye1, ref_dye2]; %#ok<NASGU>

    net_file = fullfile(out_dir, 'pairwise_reference_net.mat');
    save(net_file, 'net', 'wl', 'reference_pair', 'roi_data', 'roi_labels');
    fprintf('Reference net saved to %s (with %d real held-out ROI images)\n', net_file, size(roi_data,4));
end
